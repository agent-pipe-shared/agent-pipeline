const purls = (result) => result.components.map((c) => c.purl);
const scoped = (result) => result.components.map((c) => [c.purl, c.scope]);
const states = (result) => result.issues.map((i) => i.state);
const noUrl = (value, label) => assert.doesNotMatch(JSON.stringify(value), /:\/\/|example\.invalid|secret/u, `${label}: no URL, host or credential is carried`);
function observe(files) { return observeSbomInputs({ tracked: Object.keys(files), read: (path) => (Object.hasOwn(files, path) ? files[path] : null) }); }

