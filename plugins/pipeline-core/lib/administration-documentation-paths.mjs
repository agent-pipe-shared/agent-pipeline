/**
 * The ONE closed set of administration and documentation paths (candidate 19, PO decision 2026-11-04 on open question 2 of
 * docs/adr/draft-authority-carry-forward-and-signed-reconcile-commit.md): a path in this set can change between a Critic-reviewed commit and
 * a later candidate without making the Critic evidence of the reviewed commit stale. Everything else is content and invalidates it.
 *
 * Why these classes, and why only these. A Critic reviews what a product does (source, scripts, configuration, schemas, tests, decisions,
 * the PRD, the Spec and the plan of a feature). A commit that changes none of that gives the reviewer nothing new to read:
 *   - record-only: the base set of lib/record-only-paths.mjs (Verify/Security records, dispatch evidence, backlog bookkeeping, the handover
 *     file, pipeline state files). Reused unchanged, so the push gate's freshness rule and this rule cannot drift apart.
 *   - documentation-markdown: a Markdown file under docs/, EXCEPT docs/adr/**. An ADR is a decision, and a decision is content.
 *   - readme: a README file inside a documentation tree (docs/, backlog/, specs/<feature>/, audit-bundles/<feature>/). The README at the
 *     repository root is deliberately NOT here: it is the product's front page, and the Critic carry-forward of the feature close (16c)
 *     already refuses it by a pinned case.
 *   - backlog: anything under backlog/ (items, status, index, transitions, evidence): process administration, no product behavior.
 *   - feature-package-generated: specs/<feature>/lifecycle.json and result.md, both generated by the feature package tools.
 *   - feature-evidence: specs/<feature>/evidence/** and
 *   - audit-bundle: audit-bundles/<feature>/** (evidence and bundles produced about a candidate, not part of it).
 * Vetoes, checked first and never overridden by a class: docs/adr/**, and specs/<feature>/evidence/critic/** (the tracked export of a
 * consumed Critic review has its own receipt-bound classifier in lib/critic-course-admission.mjs; a path class must not become a second,
 * weaker way in for a forged or extended export), and the Critic disposition addenda under evidence/ together with the Markdown evidence
 * they digest (criticAddendumOnlyCommit binds them to an immutable dispatch record; a path class must not weaken that either).
 * Content for certain (not listed above, therefore outside the set): source, scripts, configuration (including project/guard-config.json),
 * schemas, tests, ADRs, agent and skill prompts, templates, the spec/PRD/plan texts of a feature (specs/<feature>/spec.md, prd.md, plan.md
 * and every other file of the feature directory that is not generated or evidence), the root README and any path not named here.
 *
 * Feature-bound paths (specs/<feature>/..., audit-bundles/<feature>/...) can be restricted to the features a caller names, so that the
 * carry-forward of one feature never admits another feature's directory.
 *
 * File modes (a symbolic link or executable file named like a document) are not visible in a path string; the range decision in
 * lib/critic-evidence-carry.mjs refuses them.
 */
import { isRecordOnlyPath } from "./record-only-paths.mjs";

const FEATURE_BOUND = /^(?:specs|audit-bundles)\/([^/]+)\//u;
const VETO = Object.freeze([
  /^docs\/adr\//u,
  /^specs\/[^/]+\/evidence\/critic(?:\/|$)/u,
  // A Critic disposition addendum and the Markdown evidence it digests are bound to an immutable dispatch record by criticAddendumOnlyCommit.
  /^(?:backlog\/)?evidence\/dispatch-critic-addendum-[^/]+\.json$/u,
  /^(?:backlog\/)?evidence\/[^/]+\.md$/u,
]);

/** Ordered: the first class that matches names the path. `id` values are pinned by tests. */
export const ADMINISTRATION_DOCUMENTATION_CLASSES = Object.freeze([
  Object.freeze({ id: "record-only", matches: (path) => isRecordOnlyPath(path) }),
  Object.freeze({ id: "documentation-markdown", matches: (path) => /^docs\/(?:[^/]+\/)*[^/]+\.md$/u.test(path) }),
  Object.freeze({ id: "readme", matches: (path) => /^(?:docs|backlog|specs\/[^/]+|audit-bundles\/[^/]+)\/(?:[^/]+\/)*README(?:\.(?:md|txt))?$/u.test(path) }),
  Object.freeze({ id: "backlog", matches: (path) => /^backlog\/.+$/u.test(path) }),
  Object.freeze({ id: "feature-package-generated", matches: (path) => /^specs\/[^/]+\/(?:lifecycle\.json|result\.md)$/u.test(path) }),
  Object.freeze({ id: "feature-evidence", matches: (path) => /^specs\/[^/]+\/evidence\/.+$/u.test(path) }),
  Object.freeze({ id: "audit-bundle", matches: (path) => /^audit-bundles\/[^/]+\/.+$/u.test(path) }),
]);

function wellFormed(path) {
  return typeof path === "string" && path.length > 0 && path.length <= 1024 && !path.includes("\\") && !path.includes("\0")
    && !path.startsWith("/") && path.split("/").every((part) => part !== "" && part !== "." && part !== "..");
}

/**
 * The class id that admits `path`, or null (content, a vetoed path, a malformed path, or a feature outside `featureIds`).
 * `featureIds` null means feature-bound paths are admitted for any feature.
 */
export function administrationDocumentationClassOf(path, { featureIds = null } = {}) {
  if (!wellFormed(path) || VETO.some((pattern) => pattern.test(path))) return null;
  const feature = FEATURE_BOUND.exec(path)?.[1];
  if (feature !== undefined && Array.isArray(featureIds) && !featureIds.includes(feature)) return null;
  return ADMINISTRATION_DOCUMENTATION_CLASSES.find((entry) => entry.matches(path))?.id ?? null;
}

export function isAdministrationDocumentationPath(path, options = {}) {
  return administrationDocumentationClassOf(path, options) !== null;
}
