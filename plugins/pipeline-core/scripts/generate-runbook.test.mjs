// Drift pin for the generated close-path runbook (C19-G5 stage 1, AC-108): the committed files must equal what the
// generator produces now from the close chain tables. Model: check-vendored-template-sync.test.mjs.
import assert from "node:assert/strict";
import test from "node:test";
import { createHash } from "node:crypto";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

import { buildRunbookFiles, RUNBOOK_FILES } from "./generate-runbook.mjs";
import { CLOSE_STEP_REQUIREMENTS } from "../lib/close-chain-guide.mjs";

const SCRIPT = fileURLToPath(new URL("./generate-runbook.mjs", import.meta.url));
const PLUGIN_ROOT = resolve(dirname(SCRIPT), "..");

test("committed runbook files equal the regenerated bytes (drift pin)", () => {
  const generated = buildRunbookFiles();
  for (const [rel, bytes] of Object.entries(generated)) {
    const committed = readFileSync(join(PLUGIN_ROOT, rel.replace(/^plugins\/pipeline-core\//, "")), "utf8");
    assert.equal(committed, bytes, `RUNBOOK-DRIFT ${rel}`);
  }
  assert.deepEqual(Object.keys(generated).sort(), [...RUNBOOK_FILES].sort());
});

test("two generations are byte-equal and carry no timestamp or absolute path", () => {
  const a = buildRunbookFiles();
  const b = buildRunbookFiles();
  assert.deepEqual(a, b);
  for (const bytes of Object.values(a)) {
    assert.ok(bytes.endsWith("}\n"));
    assert.doesNotMatch(bytes, /\/home\/|[A-Za-z]:\\|\d{4}-\d{2}-\d{2}T/);
  }
});

test("every phase of CLOSE_STEP_REQUIREMENTS appears exactly once as a step id", () => {
  const doc = JSON.parse(buildRunbookFiles()["plugins/pipeline-core/runbooks/close-path.v1.json"]);
  assert.equal(doc.schema, "pipeline.runbook.v1");
  assert.equal(doc.pathId, "close");
  const ids = doc.steps.map((s) => s.id);
  for (const phase of Object.keys(CLOSE_STEP_REQUIREMENTS)) {
    assert.equal(ids.filter((id) => id === phase).length, 1, phase);
  }
  assert.equal(new Set(ids).size, ids.length);
  for (const s of doc.steps) {
    for (const k of ["id", "who", "command", "needs", "evidenceSchema", "producer", "humanGate", "next"]) assert.ok(k in s, `${s.id} lacks ${k}`);
  }
  assert.deepEqual(doc.notGenerated.length, 2);
  const forkStep = doc.steps.find((s) => s.id === "final-verify-green");
  assert.ok(forkStep.next.length > 1, "forks stay visible");
});

test("index lists the path file with its sha256", () => {
  const files = buildRunbookFiles();
  const idx = JSON.parse(files["plugins/pipeline-core/runbooks/index.v1.json"]);
  assert.equal(idx.schema, "pipeline.runbook-index.v1");
  assert.equal(idx.paths.length, 1);
  const e = idx.paths[0];
  assert.equal(e.pathId, "close");
  assert.equal(e.path, "plugins/pipeline-core/runbooks/close-path.v1.json");
  assert.equal(e.schema, "pipeline.runbook.v1");
  assert.equal(e.sha256, createHash("sha256").update(files[e.path]).digest("hex"));
});

test("--check exits 0 on equal bytes, 2 with RUNBOOK-DRIFT on a differing file, and writes nothing", () => {
  const root = mkdtempSync(join(tmpdir(), "generate-runbook-test-"));
  try {
    mkdirSync(join(root, "runbooks"), { recursive: true });
    const files = buildRunbookFiles();
    for (const [rel, bytes] of Object.entries(files)) writeFileSync(join(root, rel.replace(/^plugins\/pipeline-core\//, "")), bytes);
    let r = spawnSync(process.execPath, [SCRIPT, "--check", "--root", root], { encoding: "utf8" });
    assert.equal(r.status, 0, r.stderr);
    writeFileSync(join(root, "runbooks/close-path.v1.json"), "{}\n");
    r = spawnSync(process.execPath, [SCRIPT, "--check", "--root", root], { encoding: "utf8" });
    assert.equal(r.status, 2);
    assert.match(r.stderr, /RUNBOOK-DRIFT.*close-path\.v1\.json/);
    assert.equal(readFileSync(join(root, "runbooks/close-path.v1.json"), "utf8"), "{}\n");
    r = spawnSync(process.execPath, [SCRIPT, "--bogus"], { encoding: "utf8" });
    assert.notEqual(r.status, 0);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("without --check the generator writes both files under --root", () => {
  const root = mkdtempSync(join(tmpdir(), "generate-runbook-test-"));
  try {
    const r = spawnSync(process.execPath, [SCRIPT, "--root", root], { encoding: "utf8" });
    assert.equal(r.status, 0, r.stderr);
    for (const [rel, bytes] of Object.entries(buildRunbookFiles())) {
      assert.equal(readFileSync(join(root, rel.replace(/^plugins\/pipeline-core\//, "")), "utf8"), bytes);
    }
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
