/**
 * generate-runbook.mjs -- writes the machine-readable close-path runbook from the close chain tables, and pins the committed copy.
 *
 * The runbook is advisory documentation for agents (nothing reads it at runtime). It is built only from the pure functions of
 * lib/close-chain-guide.mjs and coordinatorNextPhases; the placeholders <root> and <id> stay as they are. The output is canonical
 * JSON (two-space indent, trailing newline) with no timestamp, no absolute path and no host data, so two runs are byte-equal.
 * The dynamic quality rows and the push-threat-model action depend on repository state and are NOT generated.
 *
 * Usage: node generate-runbook.mjs [--check] [--root <dir>]
 *   --root   plugin directory that holds runbooks/ (default: this plugin's own directory)
 *   (none)   writes runbooks/close-path.v1.json and runbooks/index.v1.json under --root
 *   --check  writes nothing; exit 0 when the committed bytes equal the generated bytes, exit 2 with RUNBOOK-DRIFT naming the file otherwise
 * Any other argument exits 1.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { isDirectInvocation } from "../lib/entrypoint.mjs";
import { CLOSE_STEP_REQUIREMENTS, describeCloseActions, describeCloseChain } from "../lib/close-chain-guide.mjs";
import { lifecycleRunbooks, PUSH_FLOW_DOC, RUNBOOK_SCHEMA, validateRunbook } from "../lib/runbook-paths.mjs";
import { coordinatorNextPhases } from "./publication-close-journal.mjs";

const PLUGIN_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PREFIX = "plugins/pipeline-core/";
const CLOSE_PATH_FILE = `${PREFIX}runbooks/close-path.v1.json`;
const INDEX_FILE = `${PREFIX}runbooks/index.v1.json`;
export const RUNBOOK_FILES = Object.freeze([CLOSE_PATH_FILE, ...["start", "plan", "implement", "push"].map((id) => `${PREFIX}runbooks/${id}-path.v1.json`), INDEX_FILE]);

const canonical = (value) => `${JSON.stringify(value, null, 2)}\n`;

function closeSteps() {
  const steps = [];
  const active = describeCloseActions("active").actions;
  const whoByPhase = new Map(describeCloseActions("checkpointed").actions.map((a) => [a.id, a.who]));
  // Actions that do not depend on dynamic state: checkpointed and the Continuity Result steps (the chain phases follow below).
  const lead = active.filter((a) => a.id === "checkpointed" || !(a.id in CLOSE_STEP_REQUIREMENTS));
  lead.forEach((a, i) => {
    steps.push({
      id: a.id, who: a.who, command: a.command, needs: [], evidenceSchema: null, producer: a.source, humanGate: a.who === "po-only",
      next: i + 1 < lead.length ? [lead[i + 1].id] : coordinatorNextPhases("checkpointed"),
    });
  });
  const chain = describeCloseChain("checkpointed");
  const toStep = (s) => ({
    id: s.phase, who: whoByPhase.get(s.phase) ?? (s.humanGate ? "po-only" : "agent"), command: s.plan, needs: s.needs,
    evidenceSchema: s.evidenceSchema, producer: s.producer, humanGate: s.humanGate, next: coordinatorNextPhases(s.phase),
  });
  for (const s of chain.remaining) steps.push(toStep(s));
  // The walk follows the first branch of each fork; the other branches are steps too, built from the same table row.
  for (const fork of chain.forks) {
    const sibling = chain.remaining.find((s) => s.phase === fork.alternatives[0]);
    for (const alt of fork.alternatives.slice(1)) {
      if (steps.some((s) => s.id === alt)) continue;
      const need = CLOSE_STEP_REQUIREMENTS[alt];
      steps.push(toStep({
        phase: alt, needs: need.flags, evidenceSchema: need.evidenceSchema, producer: need.producer, humanGate: need.humanGate,
        plan: `${sibling.plan.replace(/ --phase .*$/, "")} --phase ${alt}${need.flags.length > 0 ? " <needs>" : ""}`,
      }));
    }
  }
  return steps;
}

const NEW_PATH_IDS = Object.freeze(["start", "plan", "implement", "push"]);
const pathFileOf = (pathId) => `${PREFIX}runbooks/${pathId}-path.v1.json`;
const readPushFlow = () => readFileSync(resolve(PLUGIN_ROOT, "..", "..", PUSH_FLOW_DOC), "utf8");

/** The generated files as { repo-relative path: canonical JSON text }. Deterministic; `pushFlowText` replaces the push-flow doc (tests). */
export function buildRunbookFiles({ pushFlowText = readPushFlow() } = {}) {
  const closePath = canonical({
    schema: "pipeline.runbook.v1",
    pathId: "close",
    generatedFrom: ["plugins/pipeline-core/lib/close-chain-guide.mjs", "plugins/pipeline-core/scripts/publication-close-journal.mjs"],
    notGenerated: ["quality-<id> rows (depend on repository state: closeQualityReadback)", "materialize-push-threat-model (depends on repository state: push threat model required and absent)"],
    steps: closeSteps(),
  });
  const lifecycle = lifecycleRunbooks({ pushFlowText });
  const files = { [CLOSE_PATH_FILE]: closePath };
  for (const pathId of NEW_PATH_IDS) {
    const problems = validateRunbook(lifecycle[pathId]);
    if (problems.length > 0) throw Object.assign(new Error(`RUNBOOK-INVALID: ${pathId}: ${problems.join("; ")}`), { code: "RUNBOOK-INVALID" });
    files[pathFileOf(pathId)] = canonical(lifecycle[pathId]);
  }
  const index = canonical({
    schema: "pipeline.runbook-index.v1",
    paths: ["close", ...NEW_PATH_IDS].map((pathId) => ({
      pathId, path: pathFileOf(pathId), schema: RUNBOOK_SCHEMA, sha256: createHash("sha256").update(files[pathFileOf(pathId)]).digest("hex"),
    })),
  });
  return { ...files, [INDEX_FILE]: index };
}

const target = (root, rel) => join(root, rel.slice(PREFIX.length));

export function main(argv = process.argv.slice(2)) {
  let check = false;
  let root = PLUGIN_ROOT;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--check") check = true;
    else if (argv[i] === "--root" && i + 1 < argv.length) root = resolve(argv[++i]);
    else {
      process.stderr.write(`error: unknown argument: ${argv[i]}\nusage: generate-runbook.mjs [--check] [--root <dir>]\n`);
      process.exitCode = 1;
      return;
    }
  }
  let files;
  try { files = buildRunbookFiles(); } catch (error) {
    process.stderr.write(`error: ${error?.message ?? "the runbooks could not be generated"}\n`);
    process.exitCode = 2;
    return;
  }
  if (check) {
    for (const [rel, bytes] of Object.entries(files)) {
      let committed = null;
      try { committed = readFileSync(target(root, rel), "utf8"); } catch { /* missing counts as drift */ }
      if (committed !== bytes) {
        process.stderr.write(`RUNBOOK-DRIFT: ${rel} differs from the generated bytes; run: node plugins/pipeline-core/scripts/generate-runbook.mjs\n`);
        process.exitCode = 2;
        return;
      }
    }
    return;
  }
  for (const [rel, bytes] of Object.entries(files)) {
    mkdirSync(dirname(target(root, rel)), { recursive: true });
    writeFileSync(target(root, rel), bytes);
  }
}

if (isDirectInvocation(import.meta.url)) main();
